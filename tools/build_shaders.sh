#!/bin/sh
# Compiles runtime/shaders/*.{vert,frag} (GLSL 450, SDL_GPU binding layout) to every bytecode the
# runtime ships and writes runtime/src/gpu/shaders_gen.h. Developer tool: the generated header is
# committed, so players need none of this.
#
#   brew install glslang spirv-cross     (or the distro packages)
#   tools/build_shaders.sh
#
# Formats: SPIR-V (Vulkan: Linux, Steam Deck, Windows) and MSL (Metal: macOS, via SPIRV-Cross).
set -eu
HERE=$(cd "$(dirname "$0")/.." && pwd)
SRC="$HERE/runtime/shaders"
OUT="$HERE/runtime/src/gpu/shaders_gen.h"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

for f in "$SRC"/*.vert "$SRC"/*.frag; do
    name=$(basename "$f" | tr . _)
    glslang -V --target-env vulkan1.0 -o "$TMP/$name.spv" "$f" >/dev/null
    # --msl-decoration-binding: [[buffer(n)]]/[[texture(n)]]/[[sampler(n)]] = GLSL binding n,
    # which is SDL_GPU's MSL layout given one resource per kind.
    spirv-cross "$TMP/$name.spv" --msl --msl-version 20100 --msl-decoration-binding \
        --output "$TMP/$name.msl"
done

python3 - "$TMP" "$OUT" <<'PY'
import os, sys
tmp, out = sys.argv[1], sys.argv[2]
names = sorted({f.rsplit('.', 1)[0] for f in os.listdir(tmp)})
lines = ['// Generated by tools/build_shaders.sh from runtime/shaders/ - do not edit.', '#pragma once', '#include <cstdint>', '']
for n in names:
    spv = open(os.path.join(tmp, n + '.spv'), 'rb').read()
    lines.append(f'alignas(4) static const uint8_t k_{n}_spv[] = {{')
    for i in range(0, len(spv), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in spv[i:i + 16]) + ',')
    lines.append('};')
    msl = open(os.path.join(tmp, n + '.msl')).read()
    lines.append(f'static const char k_{n}_msl[] = R"MSL(' + msl + ')MSL";')
    lines.append('')
open(out, 'w').write('\n'.join(lines))
PY
echo "wrote $OUT"
