#!/usr/bin/env python3
"""Writes runtime/src/game/text_keep.inc: the parts of game.EXE's x86 .text that the translated code still
reads (docs/notes/25-psp-port.md, PSP-1000 memory). The rest of .text is never read or executed, and the
compact guest layout gives it to the guest heap (memory.cpp, donate_text_to_heap).

    gen_text_keep.py build/analysis/discovery.json extracted/app/game.EXE > runtime/src/game/text_keep.inc

Kept: jump tables and their byte index tables (translated switches read them), the self-modifying
rasterizer (docs/05), and every memory operand with a .text displacement (indexed ones: up to the
next function, at most 1 KB; e.g. the CRT's memcpy jump tables).
Each range is padded by 16 bytes and aligned to 16.
"""
import json
import sys

import capstone
import pefile
from capstone import x86

disc, exe = sys.argv[1], sys.argv[2]
d = json.load(open(disc))
pe = pefile.PE(exe)
base = pe.OPTIONAL_HEADER.ImageBase
text = [s for s in pe.sections if s.Name.startswith(b".text")][0]
code = text.get_data()
lo = base + text.VirtualAddress
hi = lo + text.Misc_VirtualSize
keep = [(0x4A2EC0, 0x4AEF10)]   # self-modifying rasterizer (VirtualProtect range at 0x4af3f0)
for jt in d["jump_tables"].values():
    t = int(jt["table"], 16)
    keep.append((t, t + 4 * len(jt["targets"])))
    if jt["index_table"]:
        a, n = jt["index_table"]
        a = int(a, 16) if isinstance(a, str) else a
        keep.append((a, a + n))
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
md.detail = True
starts = sorted(int(f, 16) for f in d["functions"])
for f, info in d["functions"].items():
    f = int(f, 16)
    for n, i in enumerate(md.disasm(code[f - lo:f - lo + 0x4000], f)):
        for op in i.operands:
            if op.type == x86.X86_OP_MEM and lo <= (op.mem.disp & 0xFFFFFFFF) < hi:
                a = op.mem.disp & 0xFFFFFFFF
                if op.mem.base == 0 and op.mem.index == 0:
                    keep.append((a, a + max(op.size, 4)))
                else:   # a table of unknown length (e.g. the CRT's memcpy jump tables): up to the next function
                    nxt = next((s for s in starts if s > a), hi)
                    keep.append((a - 64, min(nxt, a + 1024)))
        if n + 1 >= info["ninsns"]:
            break
ranges = []
for a, b in sorted((max(lo, (a - 16) & ~15), min(hi, (b + 16 + 15) & ~15)) for a, b in keep):
    if ranges and a <= ranges[-1][1]:
        ranges[-1][1] = max(ranges[-1][1], b)
    else:
        ranges.append([a, b])
print("// Generated by scripts/psp/gen_text_keep.py from the GOG game.EXE analysis - do not edit.")
print(f"// .text [0x{lo:x}, 0x{hi:x}); kept {sum(b - a for a, b in ranges)} bytes in {len(ranges)} ranges.")
print(f"constexpr uint32_t TEXT_LO = 0x{lo:x}, TEXT_HI = 0x{hi:x};")
print("constexpr uint32_t TEXT_KEEP[][2] = {")
for a, b in ranges:
    print(f"    {{0x{a:x}, 0x{b:x}}},")
print("};")
